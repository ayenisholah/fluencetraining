import * as path from "node:path";
import { fileURLToPath } from "node:url";
import { CfnOutput, Duration, RemovalPolicy, SecretValue, Stack, Tags, type StackProps } from "aws-cdk-lib";
import * as backup from "aws-cdk-lib/aws-backup";
import * as cloudwatch from "aws-cdk-lib/aws-cloudwatch";
import * as cwActions from "aws-cdk-lib/aws-cloudwatch-actions";
import * as ec2 from "aws-cdk-lib/aws-ec2";
import * as events from "aws-cdk-lib/aws-events";
import * as iam from "aws-cdk-lib/aws-iam";
import * as logs from "aws-cdk-lib/aws-logs";
import * as s3assets from "aws-cdk-lib/aws-s3-assets";
import * as secretsmanager from "aws-cdk-lib/aws-secretsmanager";
import * as ssm from "aws-cdk-lib/aws-ssm";
import type { Construct } from "constructs";
import { config, GENERATED_SECRETS } from "./config";

const repoRoot = path.join(path.dirname(fileURLToPath(import.meta.url)), "..", "..");

/** Log groups the containers write to through Docker's awslogs driver. */
export const LOG_GROUPS = ["caddy", "convex", "n8n", "mailpit"] as const;

/**
 * The production host: one EC2 instance running Convex, n8n, Mailpit and
 * Caddy (TLS) with docker compose. Stateful, so it lives in its own stack
 * with termination protection.
 */
export class BackendStack extends Stack {
  readonly instance: ec2.Instance;
  readonly baseDomain: string;
  readonly convexUrl: string;
  readonly logGroups: Record<(typeof LOG_GROUPS)[number], logs.LogGroup>;

  constructor(scope: Construct, id: string, props: StackProps) {
    super(scope, id, { ...props, terminationProtection: true });

    const vpc = ec2.Vpc.fromLookup(this, "DefaultVpc", { isDefault: true });

    // ── Secrets: generated by CloudFormation, never seen by a person ─────────
    const secrets = Object.fromEntries(
      GENERATED_SECRETS.map((name) => [
        name,
        new secretsmanager.Secret(this, `Secret${name}`, {
          secretName: `${config.secretPrefix}/${name}`,
          description: `LendLoop production ${name} (generated).`,
          generateSecretString: { passwordLength: 64, excludePunctuation: true },
          removalPolicy: RemovalPolicy.RETAIN,
        }),
      ]),
    ) as Record<(typeof GENERATED_SECRETS)[number], secretsmanager.Secret>;
    // Written by the host once Convex is up (bootstrap.sh); "pending" until then.
    const adminKey = new secretsmanager.Secret(this, "SecretConvexAdminKey", {
      secretName: `${config.secretPrefix}/CONVEX_ADMIN_KEY`,
      description: "LendLoop production Convex admin key (written by the host on first boot).",
      secretStringValue: SecretValue.unsafePlainText("pending"),
      removalPolicy: RemovalPolicy.RETAIN,
    });

    // ── Logs ─────────────────────────────────────────────────────────────────
    this.logGroups = Object.fromEntries(
      LOG_GROUPS.map((name) => [
        name,
        new logs.LogGroup(this, `Logs${name}`, {
          logGroupName: `/lendloop/prod/${name}`,
          retention: logs.RetentionDays.ONE_MONTH,
          removalPolicy: RemovalPolicy.RETAIN,
        }),
      ]),
    ) as BackendStack["logGroups"];

    // ── Code bundles (compose file, Caddyfile, scripts; n8n workflows) ───────
    const bundle = new s3assets.Asset(this, "Ec2Bundle", { path: path.join(repoRoot, "deploy", "ec2") });
    const n8nBundle = new s3assets.Asset(this, "N8nBundle", {
      path: path.join(repoRoot, "n8n"),
      exclude: ["*.test.ts", "*.ts"],
    });
    const bundleParam = new ssm.StringParameter(this, "BundleParam", {
      parameterName: "/lendloop/prod/bundle/ec2",
      stringValue: bundle.s3ObjectUrl,
    });
    const n8nBundleParam = new ssm.StringParameter(this, "N8nBundleParam", {
      parameterName: "/lendloop/prod/bundle/n8n",
      stringValue: n8nBundle.s3ObjectUrl,
    });

    // ── Network: only 80/443 in; no SSH (Session Manager instead) ────────────
    const sg = new ec2.SecurityGroup(this, "WebSg", {
      vpc,
      description: "LendLoop host: HTTP/HTTPS only (Caddy). No SSH; use SSM Session Manager.",
      allowAllOutbound: true,
    });
    for (const port of [80, 443]) {
      sg.addIngressRule(ec2.Peer.anyIpv4(), ec2.Port.tcp(port), `HTTP${port === 443 ? "S" : ""} from anywhere`);
      sg.addIngressRule(ec2.Peer.anyIpv6(), ec2.Port.tcp(port), `HTTP${port === 443 ? "S" : ""} from anywhere (IPv6)`);
    }

    const eip = new ec2.CfnEIP(this, "Eip", { domain: "vpc", tags: [{ key: "Name", value: "lendloop-prod" }] });
    this.baseDomain = `${eip.attrPublicIp}.sslip.io`;
    this.convexUrl = `https://convex.${this.baseDomain}`;

    // ── Instance role: least privilege for what the host does ───────────────
    const role = new iam.Role(this, "InstanceRole", {
      assumedBy: new iam.ServicePrincipal("ec2.amazonaws.com"),
      description: "LendLoop production host",
      managedPolicies: [
        iam.ManagedPolicy.fromAwsManagedPolicyName("AmazonSSMManagedInstanceCore"),
        iam.ManagedPolicy.fromAwsManagedPolicyName("CloudWatchAgentServerPolicy"),
      ],
    });
    for (const group of Object.values(this.logGroups)) group.grantWrite(role);
    role.addToPolicy(
      new iam.PolicyStatement({
        actions: ["cloudwatch:PutMetricData"],
        resources: ["*"],
        conditions: { StringEquals: { "cloudwatch:namespace": config.metricsNamespace } },
      }),
    );
    for (const secret of Object.values(secrets)) secret.grantRead(role);
    adminKey.grantRead(role);
    adminKey.grantWrite(role);
    bundle.grantRead(role);
    n8nBundle.grantRead(role);
    bundleParam.grantRead(role);
    n8nBundleParam.grantRead(role);
    role.addToPolicy(
      new iam.PolicyStatement({
        actions: ["ssm:GetParameter"],
        resources: [`arn:aws:ssm:${this.region}:${this.account}:parameter/lendloop/prod/app-url`],
      }),
    );

    // ── Boot: install Docker and the CloudWatch agent, then run bootstrap.sh ─
    const userData = ec2.UserData.forLinux();
    userData.addCommands(
      "set -euxo pipefail",
      "dnf install -y docker jq unzip amazon-cloudwatch-agent",
      "mkdir -p /usr/local/lib/docker/cli-plugins",
      'curl -fsSL "https://github.com/docker/compose/releases/download/v2.39.4/docker-compose-linux-aarch64" -o /usr/local/lib/docker/cli-plugins/docker-compose',
      "chmod +x /usr/local/lib/docker/cli-plugins/docker-compose",
      "systemctl enable --now docker",
      // Host metrics the default EC2 metrics lack: memory and disk.
      `cat > /opt/aws/amazon-cloudwatch-agent/etc/amazon-cloudwatch-agent.json <<'CWA'
${JSON.stringify(
  {
    agent: { metrics_collection_interval: 60 },
    metrics: {
      namespace: config.metricsNamespace,
      append_dimensions: { InstanceId: "${aws:InstanceId}" },
      aggregation_dimensions: [["InstanceId"]],
      metrics_collected: {
        mem: { measurement: ["mem_used_percent"] },
        disk: { measurement: ["used_percent"], resources: ["/"], drop_device: true },
      },
    },
  },
  null,
  2,
)}
CWA`,
      "/opt/aws/amazon-cloudwatch-agent/bin/amazon-cloudwatch-agent-ctl -a fetch-config -m ec2 -s -c file:/opt/aws/amazon-cloudwatch-agent/etc/amazon-cloudwatch-agent.json",
      // Settings bootstrap.sh needs, kept for later re-runs via SSM.
      `cat > /etc/lendloop.env <<ENV
AWS_REGION=${this.region}
BASE_DOMAIN=${this.baseDomain}
SECRET_PREFIX=${config.secretPrefix}
BUNDLE_PARAM=${bundleParam.parameterName}
N8N_BUNDLE_PARAM=${n8nBundleParam.parameterName}
ENV`,
      // bootstrap.sh comes from the bundle; fetch it once to run it.
      `aws s3 cp --region ${this.region} ${bundle.s3ObjectUrl} /tmp/ec2.zip --only-show-errors`,
      "mkdir -p /opt/lendloop && unzip -oq /tmp/ec2.zip -d /opt/lendloop && chmod +x /opt/lendloop/*.sh",
      "set -a; . /etc/lendloop.env; set +a; /opt/lendloop/bootstrap.sh",
    );

    this.instance = new ec2.Instance(this, "Host", {
      vpc,
      vpcSubnets: { subnetType: ec2.SubnetType.PUBLIC },
      instanceType: new ec2.InstanceType(config.instanceType),
      // Pinned in cdk.context.json: a new AMI must never silently replace the
      // host (and its data). Refresh deliberately with `cdk context --reset`.
      machineImage: ec2.MachineImage.latestAmazonLinux2023({ cpuType: ec2.AmazonLinuxCpuType.ARM_64, cachedInContext: true }),
      securityGroup: sg,
      role,
      userData,
      requireImdsv2: true,
      detailedMonitoring: false,
      blockDevices: [
        {
          deviceName: "/dev/xvda",
          volume: ec2.BlockDeviceVolume.ebs(30, { volumeType: ec2.EbsDeviceVolumeType.GP3, encrypted: true }),
        },
      ],
      instanceName: "lendloop-prod",
    });
    (this.instance.node.defaultChild as ec2.CfnInstance).disableApiTermination = true;
    // Containers don't call AWS (the awslogs driver uses dockerd's host
    // credentials), so IMDS stays at one hop.
    new ec2.CfnEIPAssociation(this, "EipAssociation", { allocationId: eip.attrAllocationId, instanceId: this.instance.instanceId });

    // ── Recovery: auto-recover on hardware failure; daily EBS snapshots ─────
    new cloudwatch.Alarm(this, "AutoRecover", {
      alarmName: "lendloop-prod-host-auto-recover",
      alarmDescription: "System status check failed: EC2 recovers the instance onto healthy hardware.",
      metric: new cloudwatch.Metric({
        namespace: "AWS/EC2",
        metricName: "StatusCheckFailed_System",
        dimensionsMap: { InstanceId: this.instance.instanceId },
        statistic: "Maximum",
        period: Duration.minutes(1),
      }),
      threshold: 0,
      comparisonOperator: cloudwatch.ComparisonOperator.GREATER_THAN_THRESHOLD,
      evaluationPeriods: 2,
      datapointsToAlarm: 2,
      treatMissingData: cloudwatch.TreatMissingData.MISSING,
    }).addAlarmAction(new cwActions.Ec2Action(cwActions.Ec2InstanceAction.RECOVER));

    const vault = new backup.BackupVault(this, "Vault", {
      backupVaultName: "lendloop-prod",
      removalPolicy: RemovalPolicy.RETAIN,
    });
    const plan = new backup.BackupPlan(this, "Plan", {
      backupPlanName: "lendloop-prod-daily",
      backupVault: vault,
      backupPlanRules: [
        new backup.BackupPlanRule({
          ruleName: "daily-7d",
          scheduleExpression: events.Schedule.cron({ hour: "2", minute: "30" }),
          deleteAfter: Duration.days(7),
        }),
      ],
    });
    plan.addSelection("Host", { resources: [backup.BackupResource.fromEc2Instance(this.instance)] });

    Tags.of(this).add("project", config.tags.project);

    new CfnOutput(this, "BaseDomain", { value: this.baseDomain });
    new CfnOutput(this, "ConvexUrl", { value: this.convexUrl });
    new CfnOutput(this, "ConvexSiteUrl", { value: `https://site.${this.baseDomain}` });
    new CfnOutput(this, "N8nUrl", { value: `https://n8n.${this.baseDomain}` });
    new CfnOutput(this, "InstanceId", { value: this.instance.instanceId });
    new CfnOutput(this, "SecretPrefix", { value: config.secretPrefix });
    new CfnOutput(this, "PublicIp", { value: eip.attrPublicIp });
  }
}
